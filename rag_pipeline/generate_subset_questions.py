"""
Build an NQ-format question set that is ANSWERABLE FROM A GIVEN ARTICLE SUBSET.

    python -m rag_pipeline.generate_subset_questions \
        data/wikiDump/articles_4000.jsonl \
        data/NQ/synthetic-subset-4000.csv

Why this exists: `data/NQ/Natural-Questions-Filtered.csv` is written against the
full KILT dump. Run it over a 4,000-article subset and almost every gold answer
is simply absent from the corpus, so recall is pinned near zero and nothing
downstream of retrieval is measuring anything. This script emits one question
per article of the subset, with a gold answer that is a verbatim span of that
article, so retrieval has a reachable target.

The questions are generated by high-precision surface patterns over the LEAD
PARAGRAPH only (never the rest of the article, where the subject of a sentence
is usually no longer the article's subject). Every emitted row is checked with
the same `has_answer` criterion the evaluator uses, against the article text —
a row that does not pass is dropped rather than shipped.

Output columns are exactly the three `loadDatasetNQ` reads —
question, long_answers, short_answers — plus wikipedia_id / wikipedia_title /
pattern, which pandas carries along and the loader ignores. They are there so a
result can be traced back to the article and the rule that produced it.
"""

