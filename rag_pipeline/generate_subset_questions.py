MONTHS = ("January|February|March|April|May|June|July|August|September|"
          "October|November|December")

# A date as Wikipedia writes it: "1 April 1979", "July 30, 1946", "April 1979",
# or a bare year. Ordered longest-first so the fuller form wins.
DATE = (r"(?:\d{1,2} (?:" + MONTHS + r") \d{3,4}"
        r"|(?:" + MONTHS + r") \d{1,2}, \d{3,4}"
        r"|(?:" + MONTHS + r") \d{3,4}"
        r"|\d{3,4})")

# Kept out of the question text: an answer is only useful if the question does
# not already contain it, and a disambiguator like "(Bangladeshi TV channel)"
# reads as noise in a question.
PAREN = re.compile(r"\s*\([^()]*\)\s*$")


def mask_parens(text: str) -> str:
    """
    Same-length copy with parenthesised spans blanked out.

    Patterns are matched against the mask and then sliced out of the ORIGINAL
    string, so offsets stay valid and the answer is always a verbatim span. The
    masking is what stops "Percy Tyson Lewis (2 October 1884, Cape Town - 30
    January 1976, Durban) was a South African cricketer" from having its copula
    found inside the parenthetical, and stops a birth-date comma from being read
    as the end of a predicate.
    """
    out = list(text)
    depth = 0
    for i, ch in enumerate(text):
        if ch == "(":
            depth += 1
        if depth:
            out[i] = " "
        if ch == ")":
            depth = max(0, depth - 1)
    return "".join(out)


def sentences(paragraph: str):
    """(sentence, offset) pairs. Split on sentence-final punctuation followed by
    a capital; deliberately conservative, since a bad split only costs a
    candidate, never correctness (answers are re-verified against the article)."""
    spans = []
    start = 0
    for m in re.finditer(r"(?<=[.!?])\s+(?=[A-Z\"'(])", paragraph):
        spans.append((paragraph[start:m.start()], start))
        start = m.end()
    spans.append((paragraph[start:], start))
    return [(s, off) for s, off in spans if s.strip()]


TRAILING = {"of", "the", "a", "an", "in", "on", "at", "to", "by", "for", "with",
            "from", "as", "and", "or", "into", "near", "his", "her", "its",
            "their", "was", "is", "were", "are", "first", "also", "which",
            "that", "who", "over", "under", "during", "between"}


def clean_answer(span: str) -> str:
    """Trim an extracted span to something a grader can match: no dangling
    punctuation, no unbalanced bracket."""
    span = span.strip().strip(",;:")
    span = re.sub(r"\s+", " ", span)
    # "published by Marvel Comics. The character first appeared..." — a captured
    # span must not run into the next sentence. Only a stop after a real word
    # counts: the one in "Lester B. Pearson Award" is an initial, not an end.
    span = re.split(r"(?<=[a-z]{2})\.\s+", span)[0]
    if span.count("(") != span.count(")"):
        span = span.replace("(", "").replace(")", "")
    if span.count('"') % 2:
        span = span.replace('"', "")
    # A word-capped predicate tends to stop mid-phrase — "first performed in".
    # A gold answer ending on a dangling preposition costs exact-match and F1
    # against any sane generated answer, and drops nothing the grader needs.
    words = span.split()
    while words and words[-1].lower().strip(".,;:") in TRAILING:
        words.pop()
    span = " ".join(words)
    return span.strip().strip(".,;:").strip()


def q(text: str) -> str:
    """NQ question surface form: lowercase, no terminal question mark — the
    dataset this imitates is written that way, and the question string is handed
    to the retriever verbatim."""
    text = re.sub(r"\s+", " ", text).strip().rstrip("?")
    return text.lower()


